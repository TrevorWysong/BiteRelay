// Writes web/src/i18n/refusals.ts: every refusal a person can meet, in
// English as its source writes it, so the app can show it in their
// language (`lib/ui/errors.ts`'s `describeError`).
//
//   - the zomes: each `guest("...")` and `guest(format!("..."))` that's a
//     sentence (it starts with a capital). A lowercase one is a diagnostic,
//     not for people; the app says something went wrong instead;
//   - the device runtime (runtime/device): its errors' `#[error("...")]`;
//   - the issuer service: each `refusal(...)`.
//
// A value in the text becomes a placeholder: `{name}` for a named one,
// `{0}`, `{1}`... by position otherwise. Every catalog must translate each
// key, keeping its placeholders (test/i18n.test.ts).
//
//   node scripts/refusals.mjs          write it
//   node scripts/refusals.mjs --check  fail if it's out of date (CI)
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(repo, "web/src/i18n/refusals.ts");

function files(dir, ext) {
  const found = [];
  for (const entry of readdirSync(join(repo, dir), { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...files(path, ext));
    else if (entry.name.endsWith(ext)) found.push(path);
  }
  return found;
}

const unescapeRust = (s) => s.replace(/\\(["\\n])/g, (_, c) => (c === "n" ? " " : c));
const unescapeJs = (s) => s.replace(/\\(["'`\\])/g, "$1");

/// A Rust format string's text, its arguments as placeholders.
function fromRustFormat(text) {
  let position = 0;
  // `{{` and `}}` are literal braces; `{name}`, `{name:?}`, `{}` arguments.
  return unescapeRust(text).replace(/\{\{|\}\}|\{([A-Za-z_][A-Za-z0-9_]*|\d*)(?::[^}]*)?\}/g, (whole, name) => {
    if (whole === "{{") return "{";
    if (whole === "}}") return "}";
    return `{${name === "" ? position++ : name}}`;
  });
}

/// A JS template literal's text, its `${...}` as placeholders by position.
function fromTemplate(text) {
  let position = 0;
  return unescapeJs(text).replace(/\$\{[^}]*\}/g, () => `{${position++}}`);
}

const isSentence = (text) => /^[A-Z]/.test(text);

function collect() {
  const texts = [];
  for (const file of [...files("dnas/relay/zomes", ".rs").filter((f) => f.includes("/coordinator/")), ...files("dnas/relay/coordinator_support/src", ".rs")]) {
    const source = readFileSync(join(repo, file), "utf8");
    for (const m of source.matchAll(/guest\(\s*"((?:[^"\\]|\\.)*)"/g)) texts.push(unescapeRust(m[1]));
    for (const m of source.matchAll(/guest\(\s*format!\(\s*"((?:[^"\\]|\\.)*)"/g)) texts.push(fromRustFormat(m[1]));
  }
  for (const file of files("runtime/device/src", ".rs")) {
    const source = readFileSync(join(repo, file), "utf8");
    for (const m of source.matchAll(/#\[error\("((?:[^"\\]|\\.)*)"\)\]/g)) texts.push(fromRustFormat(m[1]));
  }
  for (const file of files("issuer/src", ".ts")) {
    const source = readFileSync(join(repo, file), "utf8");
    for (const m of source.matchAll(/\brefusal\(\s*(?:"((?:[^"\\]|\\.)*)"|`((?:[^`\\]|\\.)*)`)\s*\)/g)) {
      texts.push(m[1] !== undefined ? unescapeJs(m[1]) : fromTemplate(m[2]));
    }
  }
  return [...new Set(texts.filter(isSentence))].sort();
}

/// A key from the first words of the text, unique among them.
function keysFor(texts) {
  const taken = new Set();
  const keys = new Map();
  for (const text of texts) {
    const slug =
      text
        .toLowerCase()
        .replace(/\{[^}]*\}/g, " ")
        .replace(/[^a-z0-9 ]+/g, " ")
        .split(/\s+/)
        .filter(Boolean)
        .slice(0, 7)
        .join("-") || "message";
    let key = `refusal.${slug}`;
    for (let n = 2; taken.has(key); n++) key = `refusal.${slug}-${n}`;
    taken.add(key);
    keys.set(text, key);
  }
  return keys;
}

function render(texts) {
  const keys = keysFor(texts);
  const lines = texts.map((text) => `  ${JSON.stringify(keys.get(text))}: ${JSON.stringify(text)},`);
  return `// Generated by web/scripts/refusals.mjs from the zomes, the device runtime
// and the issuer service -- don't edit: change the source, then run it.
// Every refusal a person can meet, in English as its source writes it;
// every catalog translates each (describeError matches the text).
export const REFUSALS = {
${lines.join("\n")}
} as const;
`;
}

const text = render(collect());
if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
    console.error("web/src/i18n/refusals.ts is out of date: run node scripts/refusals.mjs (in web/), then translate any new refusal in each catalog.");
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
  console.log(`refusals: wrote ${text.split("\n").filter((l) => l.startsWith('  "')).length} to web/src/i18n/refusals.ts`);
}
